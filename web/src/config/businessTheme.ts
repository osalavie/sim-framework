/**
 * 商务风格 · Naive UI 覆盖工厂
 *
 * 与纸上海洋的硬编码常量分开维护：纸上海洋保持原样，商务风格只读取调色盘。
 * 描边统一走 `--po-border*`，颜色全部输出 hex / rgba，满足 Naive UI 的派生要求。
 */

function parseHex(value: string): [number, number, number] {
  const hex = value.replace('#', '').trim()
  const full =
    hex.length === 3
      ? hex
          .split('')
          .map((part) => part + part)
          .join('')
      : hex
  const numeric = Number.parseInt(full, 16)
  return [(numeric >> 16) & 255, (numeric >> 8) & 255, numeric & 255]
}

function toRgba(value: string, alpha: number): string {
  if (value.startsWith('rgba') || value.startsWith('rgb')) return value
  const [r, g, b] = parseHex(value)
  return `rgba(${r}, ${g}, ${b}, ${alpha})`
}

/** 按比例向白或黑混合，用于派生语义色的 hover / pressed。 */
function shift(value: string, amount: number, dark: boolean): string {
  const [r, g, b] = parseHex(value)
  const target = dark ? 255 : 0
  const mix = (channel: number) => Math.round(channel + (target - channel) * amount)
  return `rgb(${mix(r)}, ${mix(g)}, ${mix(b)})`
}

